"""Write each skill's embedded code blocks to <out>/<skill>/NN_<heading>.<ext> (default out: extracted/,
which git ignores: it's generated, never edited). Fences count only at line start. Scripts under a skill's
scripts/ folder are copied alongside. With --zips, also rebuild upload/<skill>.zip (one per skill, for
uploading to claude.ai). Only the output folders are written; skill sources are never touched.

    python3 tools_extract.py [--out DIR] [--zips]
"""
import argparse, re, pathlib, shutil, sys, zipfile

HERE = pathlib.Path(__file__).resolve().parent
CHECKOUT = (HERE.parent / "skills" / "handoff-ledger").is_dir()
ROOT = HERE.parent if CHECKOUT else HERE   # a checkout (tools/ next to skills/), or the installed package
# Default outputs: inside a checkout (git ignores them); for an installed package, the current folder.
DEFAULT_OUT = ROOT / "extracted" if CHECKOUT else pathlib.Path.cwd() / "relay-kit-extracted"
DEFAULT_UP = ROOT / "upload" if CHECKOUT else pathlib.Path.cwd() / "relay-kit-upload"
EXT = {"javascript": "js", "js": "js", "python": "py", "py": "py", "bash": "sh", "sh": "sh"}


MARK = ".tools_extract-output"   # written into every folder this tool fills; only such folders are replaced


def safe_output(out, root=ROOT):
    """An output folder this tool may delete and rewrite: one that doesn't exist yet, is empty,
    carries this tool's marker file, or is one of its own default folders (extracted/, upload/).
    Anything else (sources, someone's documents, a folder of untracked drafts, a symlink to one)
    is refused. Raises ValueError."""
    given = pathlib.Path(out)
    out = given.resolve()   # follows a symlink: the target is what would be deleted
    root = root.resolve()
    if out == root or out in root.parents or out == pathlib.Path(out.anchor):
        raise ValueError(f"refusing to write to {out}: it contains the repository")
    if out.exists() and not out.is_dir():
        raise ValueError(f"refusing to write to {out}: it's a file")
    own = CHECKOUT and out in (root / "extracted", root / "upload")   # a checkout's own git-ignored folders
    if out.exists() and any(out.iterdir()) and not (out / MARK).exists() and not own:
        raise ValueError(f"refusing to replace {out}: it isn't empty and wasn't made by this tool")
    if any(out.rglob("SKILL.md")) if out.exists() else False:
        raise ValueError(f"refusing to write to {out}: it holds SKILL.md sources")
    return out


def mark(out):
    out.mkdir(parents=True, exist_ok=True)
    (out / MARK).write_text("Generated by tools_extract.py; this folder is replaced on each run.\n", encoding="utf-8")


def extract(out_root, root=ROOT):
    out_root = safe_output(out_root, root)
    shutil.rmtree(out_root, ignore_errors=True)
    mark(out_root)
    for sk in sorted((root / "skills").iterdir()):
        lines = (sk / "SKILL.md").read_text(encoding="utf-8").splitlines(keepends=True)
        i = n = 0; head = "block"
        while i < len(lines):
            l = lines[i]
            if l.startswith("#"): head = l.lstrip("#").strip()
            m = re.match(r"^```(\w+)\s*$", l)
            if m:
                j = i + 1
                while j < len(lines) and not re.match(r"^```\s*$", lines[j]): j += 1
                if m.group(1) in EXT:
                    n += 1
                    name = re.sub(r"[^\w]+", "_", re.sub(r"\.(js|py)\b", "", head)).strip("_")
                    out = out_root / sk.name / f"{n:02d}_{name}.{EXT[m.group(1)]}"
                    out.parent.mkdir(parents=True, exist_ok=True)
                    out.write_text("".join(lines[i + 1:j]), encoding="utf-8")
                i = j
            i += 1
        for s in (sk / "scripts").glob("*") if (sk / "scripts").is_dir() else []:
            if s.suffix in (".py", ".js"):
                (out_root / sk.name).mkdir(parents=True, exist_ok=True)
                shutil.copy2(s, out_root / sk.name / s.name)
    return sorted(f for f in out_root.rglob("*") if f.is_file() and f.name != MARK)


def build_zips(up, root=ROOT):
    up = safe_output(up, root)
    shutil.rmtree(up, ignore_errors=True); mark(up)
    for sk in sorted((root / "skills").iterdir()):
        with zipfile.ZipFile(up / f"{sk.name}.zip", "w", zipfile.ZIP_DEFLATED) as z:
            for f in sorted(sk.rglob("*")):
                if f.is_file() and "__pycache__" not in f.parts:
                    z.write(f, f.relative_to(root / "skills"))
    return sorted(up.glob("*.zip"))


def main(argv):
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--out", type=pathlib.Path, default=DEFAULT_OUT)
    ap.add_argument("--zips", action="store_true")
    a, _ = ap.parse_known_args(argv)   # unknown arguments were ignored before; still are
    try:
        files = extract(a.out)
        zips = build_zips(DEFAULT_UP) if a.zips else None
    except ValueError as e:
        sys.exit(f"refused: {e}")
    out = a.out.resolve()
    for f in files:
        print(f.relative_to(out.parent) if out.is_relative_to(ROOT) else f)
    if zips is not None:
        print(f"rebuilt {len(zips)} upload zips")


if __name__ == "__main__":
    main(sys.argv[1:])
